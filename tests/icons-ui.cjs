const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const {pathToFileURL}=require('node:url');const path=require('node:path');const fs=require('node:fs');const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try {
    const page=await browser.newPage({viewport:{width:800,height:1300}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve(__dirname,'../preview.html')).href);
    await page.evaluate(()=>localStorage.clear());await page.reload();
    await page.getByRole('button',{name:'创建我的第一张棋盘',exact:true}).click();
    await page.getByLabel('棋盘名称',{exact:true}).fill('图标自动搭配 · 示例');
    await page.getByLabel('棋盘尺寸',{exact:true}).selectOption('3');
    await page.getByRole('button',{name:'创建棋盘',exact:true}).click();
    await page.getByRole('textbox',{name:'快速输入待办',exact:true}).fill('读十页书\n散步 20 分钟\n推进工作项目');
    await page.getByRole('textbox',{name:'快速输入待办',exact:true}).press('Enter');
    await page.waitForFunction(()=>document.querySelectorAll('.bg-cell:not(.is-empty)').length===3);
    assert.deepEqual(await page.locator('.bg-cell:not(.is-empty) .bg-cell-emoji').allTextContents(),['📖','🏃','💻']);
    await page.getByRole('button',{name:'编辑内容',exact:true}).click();
    await page.getByLabel('1号格事项名称',{exact:true}).fill('喝一杯咖啡');
    await page.getByLabel('1号格事项名称',{exact:true}).press('Enter');
    await page.waitForFunction(()=>document.querySelector('.bg-cell-emoji').textContent==='☕');
    await page.getByRole('button',{name:'1号格图标和备注',exact:true}).click();
    assert.equal(await page.getByLabel('按事项内容自动搭配图标',{exact:true}).isChecked(),true);
    await page.getByLabel('格子图标',{exact:true}).fill('🦊');
    assert.equal(await page.getByLabel('按事项内容自动搭配图标',{exact:true}).isChecked(),false);
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.getByLabel('1号格事项名称',{exact:true}).fill('看书');
    await page.getByLabel('1号格事项名称',{exact:true}).press('Enter');
    await page.waitForFunction(()=>!window.screenApp.saving.size);assert.equal(await page.locator('.bg-cell-emoji').first().textContent(),'🦊');
    await page.getByRole('button',{name:'1号格图标和备注',exact:true}).click();
    await page.getByLabel('按事项内容自动搭配图标',{exact:true}).check();
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('.bg-cell-emoji').textContent==='📖');
    await page.getByRole('button',{name:'✓ 完成编辑',exact:true}).click();
    await page.locator('.bg-cell').nth(3).click();
    await page.getByLabel('要做的小事',{exact:true}).fill('给植物浇水');
    assert.equal(await page.getByLabel('格子图标',{exact:true}).inputValue(),'🪴');
    await page.getByRole('button',{name:'保存',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.bg-cell:not(.is-empty)').length===4);
    await page.getByRole('button',{name:'批量添加',exact:true}).click();
    await page.getByLabel('事项内容',{exact:true}).fill('普通小事\n普通小事\n普通小事\n写复盘报告\n处理邮件');
    await page.getByRole('button',{name:'填入空格',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.bg-cell:not(.is-empty)').length===9);
    const before=await page.locator('.bg-cell-emoji').allTextContents();assert.equal(new Set(before).size,9);
    await page.locator('.bg-cell').first().click();await page.waitForFunction(()=>document.querySelectorAll('.is-done').length===1);
    await page.reload();await page.locator('.is-done').waitFor();assert.deepEqual(await page.locator('.bg-cell-emoji').allTextContents(),before);
    const qa=path.resolve(__dirname,'../../qa');fs.mkdirSync(qa,{recursive:true});
    await page.screenshot({path:path.join(qa,'automatic-icons.png'),fullPage:true});
    await page.getByRole('button',{name:'编辑内容',exact:true}).click();
    await page.getByRole('button',{name:'1号格图标和备注',exact:true}).click();
    await page.setViewportSize({width:390,height:1100});
    await page.screenshot({path:path.join(qa,'automatic-icons-mobile-detail.png'),fullPage:true});
    assert.equal(await page.locator('dialog').evaluate(e=>e.scrollWidth>e.clientWidth+1),false);
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(qa,'icons-results.json'),JSON.stringify({passed:true,checks:['quick-add-icons','inline-auto-rename','manual-retained','opt-back-into-auto','new-cell-preview','bulk-variety','reload-and-completion-stability','mobile-dialog'],browserErrors:errors},null,2));
    console.log('Automatic icon UI verification passed.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
